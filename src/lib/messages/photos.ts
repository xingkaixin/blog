/** 英文版没有相册英文名，相册 id 本身就是城市的英文或拼音，如 chiang-mai → Chiang Mai。 */
export function englishAlbumTitle(albumId: string): string {
  return albumId
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}
